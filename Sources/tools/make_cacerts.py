#!/usr/bin/env python3
"""Write the root CAs NEMESIS ships to boot/cacerts in Android's format:
<subject_hash_old>.N holding the PEM followed by `openssl x509 -text`.
The head unit (Android 4.4) only gets the files it does not have."""
from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "manager" / "res" / "raw" / "nemesis_roots.pem"

# Current public roots behind most HTTPS sites (Let's Encrypt, Google,
# Amazon, Cloudflare, DigiCert, Sectigo, GlobalSign, Microsoft, Certum).
ROOTS = [
    "ISRG_Root_X1",
    "ISRG_Root_X2",
    "GTS_Root_R1",
    "GTS_Root_R3",
    "GTS_Root_R4",
    "Amazon_Root_CA_1",
    "Amazon_Root_CA_2",
    "Amazon_Root_CA_3",
    "Amazon_Root_CA_4",
    "DigiCert_Global_Root_G2",
    "DigiCert_Global_Root_G3",
    "DigiCert_TLS_RSA4096_Root_G5",
    "DigiCert_TLS_ECC_P384_Root_G5",
    "USERTrust_RSA_Certification_Authority",
    "USERTrust_ECC_Certification_Authority",
    "Sectigo_Public_Server_Authentication_Root_R46",
    "Sectigo_Public_Server_Authentication_Root_E46",
    "GlobalSign_Root_CA_-_R3",
    "GlobalSign_Root_CA_-_R6",
    "GlobalSign_ECC_Root_CA_-_R5",
    "Microsoft_RSA_Root_Certificate_Authority_2017",
    "Microsoft_ECC_Root_Certificate_Authority_2017",
    "Certum_Trusted_Network_CA_2",
]


def openssl(*args: str, data: bytes) -> bytes:
    return subprocess.run(["openssl", "x509", *args], input=data, check=True, capture_output=True).stdout


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, default=Path("/etc/ssl/certs"))
    ap.add_argument("-o", "--output", type=Path, default=ROOT / "boot" / "cacerts")
    args = ap.parse_args()
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.[0-9]"):
        old.unlink()
    missing = []
    names = []
    bundle = []
    for root in ROOTS:
        src = args.source / f"{root}.pem"
        if not src.is_file():
            missing.append(root)
            continue
        raw = src.read_bytes()
        pem = openssl("-outform", "PEM", data=raw)
        text = openssl("-noout", "-text", "-fingerprint", "-sha1", data=raw)
        h = openssl("-noout", "-subject_hash_old", data=raw).decode().strip()
        n = 0
        while (out / f"{h}.{n}").exists():
            n += 1
        name = f"{h}.{n}"
        (out / name).write_bytes(pem + text)
        bundle.append(pem)
        names.append(f"{name}  {root}")
    (out / "README").write_text(
        "Generated by tools/make_cacerts.py. NEMESIS copies each <hash>.N here into\n"
        "/system/etc/security/cacerts when the unit lacks it, and lists the files it\n"
        "added in /data/nemesis/owned-cacerts. Wipe removes only those.\n\n"
        + "\n".join(names) + "\n",
        encoding="utf-8",
    )
    # PEM only: the Manager trusts these before they reach the system store.
    RAW.parent.mkdir(parents=True, exist_ok=True)
    RAW.write_bytes(b"".join(bundle))
    print(f"wrote {len(names)} roots to {out} and {RAW}")
    if missing:
        raise SystemExit("missing from source: " + ", ".join(missing))


if __name__ == "__main__":
    main()
